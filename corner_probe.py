#!/usr/bin/env python3
"""
=============================================================================
SG13G2 gm/ID Toolbox | CORNER PROBE
=============================================================================
    python3 corner_probe.py

Answers one question before you spend 8 hours per corner:

    how many full sweeps do we actually need?

A PDK corner name has two letters, one per device type, so mos_sf is
normally "slow NMOS, fast PMOS". The first guess was that the second
letter is PMOS-only and mos_sf would therefore be the SAME NMOS as
mos_ss. Measured on IHP SG13G2 it is not: mos_sf shifts this NMOS by
EXACTLY HALF of what mos_ss does, and so does mos_fs against mos_ff.
They are interior points on one axis, not independent directions.

So the question this script answers is not "are any two identical" but
the more useful one:

    which sections are independent directions, and which are already
    bounded by another one?

What a corner physically does is move VTH, so VTH is what gets compared.
Comparing ID instead is a trap: in subthreshold ID is exp(dVTH / n.Ut),
so a 50 mV shift shows up as +800 % and every pair looks wildly
different, including a pair that is bit-identical. The first version of
this script did exactly that and reported mos_tt_stat as 78 % away from
mos_tt, which cannot be true; that is how the error was found. ID is
still reported, but only where ID is a real current, and the
subthreshold blow-up is printed separately and labelled.

The section names are read OUT OF THE LIBRARY FILE, not assumed. Each
corner runs as its own standalone netlist, same bias topology and same
save list as the sweep that built the TT table, so the numbers are
comparable by construction.
"""

import os
import re
import subprocess
import sys
import numpy as np

# This script predates any table, so unlike the other generators it has
# nothing to read the device from: it runs BEFORE the sweeps, to decide
# how many corners are worth sweeping at all. So the device is an
# argument here, and only here.
#     python3 corner_probe.py          the hv device, as before
#     python3 corner_probe.py lv       the lv one
from make_sweep import (FLAVOUR, TEMP_NOM, parse_temp,
                        applied, body)                           # noqa: E402

# This one runs BEFORE any table exists, so the temperature has
# to come from the command line -- there is no meta.json to read.
_ARGS, TEMP = parse_temp(sys.argv[1:])
_FLAV = next((a for a in _ARGS if a in FLAVOUR), "hv")
CORE = FLAVOUR[_FLAV]["core"]
PDK_LIB = FLAVOUR[_FLAV]["lib"]
DEVICE = FLAVOUR[_FLAV]["device"]
W_NOM, NG = 10.0e-6, 5

COLS = ["vgs", "vds", "vsb", "leff", "ids", "gm", "gds",
        "cgg", "cgsol", "cgdol", "fug", "vth", "vdss"]

# Below this the OP solution is junction leakage plus solver residue, so a
# relative comparison of two corners there measures nothing. The first
# version of this script compared ids over ALL points and reported
# mos_tt_stat as 78 % different from mos_tt, which is how the mistake was
# caught: mos_tt_stat IS mos_tt at nominal.
ID_FLOOR = 1e-9

# L outer, bias inner: alterparam + reset happens once per L.
L_LIST = [0.45e-6, 0.6e-6, 1.0e-6, 3.0e-6, 10.0e-6]

#        VGS   VDS   VSB      what it probes
BIAS = [(0.50, 0.90, 0.00),   # weak inversion, where VTH shift is amplified
        (0.75, 0.90, 0.00),   # sub-threshold / moderate knee
        (1.20, 0.90, 0.00),   # moderate
        (2.00, 0.90, 0.00),   # strong
        (2.80, 0.90, 0.00),   # strong, near VGS max
        (0.75, 0.90, 1.50),   # body effect x corner
        (1.20, 0.90, 1.50),
        (1.20, 0.10, 0.00)]   # triode / Ron


# ----------------------------------------------------------------------
def sections(path):
    """
    Section names defined in a .lib file.

    A DEFINITION is '.lib <name>' (one token). An INCLUDE is
    '.lib <file> <section>' (two tokens). Only the first kind names a
    section this file can provide, so the one-token form is the one to
    collect.
    """
    if not os.path.exists(path):
        sys.exit(f"library not found: {path}\n"
                 "edit PDK_LIB at the top of this script")
    out = []
    with open(path, errors="replace") as fh:
        for line in fh:
            m = re.match(r"\s*\.lib\s+(\S+)\s*$", line, re.I)
            if m:
                out.append(m.group(1))
    return out


def netlist(corner, fname):
    o = []
    A = o.append
    A(f"* SG13G2 gm/ID Toolbox corner probe : {corner}")
    A("* standalone netlist, generated by corner_probe.py")
    A("")
    A(f".lib {PDK_LIB} {corner}")
    A("")
    A(f".param w  = {W_NOM:.6g}")
    A(f".param l  = {L_LIST[0]:.6g}")
    A(f".param ng = {NG}")
    A("")
    A(f".options TEMP={TEMP:g}")
    A("")
    A("* same bias topology as the sweep that built the LUT:")
    A("*   S is the reference, B is driven negative")
    A("Vgs g 0 dc 0")
    A("Vds d 0 dc 0")
    A("Vs  s 0 dc 0")
    A("Vb  b 0 dc 0")
    A(f"XM1 d g s b {DEVICE} w={{w}} l={{l}} ng={{ng}} m=1")
    A("")
    for c in COLS:
        A(f".save {CORE}[{c}]")
    A("")
    A(".control")
    A("")
    A(f"shell rm -f {fname}")
    A("")
    vecs = " ".join("p_" + c for c in COLS)
    for L in L_LIST:
        A("")
        A(f"alterparam l = {L:.6e}")
        A("reset")
        for vgs, vds, vsb in BIAS:
            # applied()/body() from make_sweep, not a local sign. This
            # file was one of the five that had its own copy of the
            # n-type convention; make_edge.py showed what that costs.
            _FD = FLAVOUR[_FLAV]
            A(f"alter Vgs dc = {applied(_FD, vgs):.6f}")
            A(f"alter Vds dc = {applied(_FD, vds):.6f}")
            A(f"alter Vb  dc = {body(_FD, vsb):.6f}")
            A("op")
            for c in COLS:
                A(f"let p_{c} = {CORE}[{c}]")
            A("set wr_singlescale")
            A("set appendwrite")
            A(f"wrdata {fname} {vecs}")
    A("")
    A("quit")
    A(".endc")
    A("")
    A(".end")
    return "\n".join(o) + "\n"


def load(data, corner, quiet=False):
    """Parse one corner's wrdata output, or None if it is unusable."""
    a = np.loadtxt(data)
    if a.ndim == 1:
        a = a[None, :]
    if a.shape[1] == len(COLS) + 1:        # wr_singlescale prepends the scale
        a = a[:, 1:]
    n = len(L_LIST) * len(BIAS)
    if a.shape[0] != n:
        print(f"  {corner:<22} got {a.shape[0]} rows, expected {n}")
        return None
    return a


def run(corner, reuse=True):
    """Returns the data table for one corner, or None if it failed."""
    spice = f"cp_{corner}.spice"
    data = f"cp_{corner}.txt"
    if reuse and os.path.exists(data):
        a = load(data, corner)
        if a is not None:
            print(f"  {corner:<22} reused {data}, {a.shape[0]} points")
            return a
    with open(spice, "w") as fh:
        fh.write(netlist(corner, data))
    r = subprocess.run(["ngspice", "-b", spice],
                       capture_output=True, text=True)
    if not os.path.exists(data):
        print(f"  {corner:<22} FAILED, no output")
        tail = (r.stderr or r.stdout).strip().splitlines()[-4:]
        for t in tail:
            print(f"      {t}")
        return None
    a = load(data, corner)
    if a is not None:
        print(f"  {corner:<22} ok, {a.shape[0]} points")
    return a


# ----------------------------------------------------------------------
def main():
    reuse = "--rerun" not in sys.argv
    secs = sections(PDK_LIB)
    print("=" * 72)
    print("sections found in")
    print(f"  {PDK_LIB}")
    print("=" * 72)
    if secs:
        for i in range(0, len(secs), 4):
            print("  " + "  ".join(f"{s:<16}" for s in secs[i:i + 4]))
    else:
        print("  (none)")

    # _mismatch and _stat are the Monte Carlo sections, not corners. They
    # are measured anyway, because the data is already there and seeing
    # _stat land on top of tt is the check that the probe itself is sane,
    # but they are kept out of the corner decision.
    def is_corner(s):
        return not any(t in s.lower() for t in ("mismatch", "stat"))

    cand = [s for s in secs if "mismatch" not in s.lower()]
    if "mos_tt" in cand:
        cand.remove("mos_tt")
        cand.insert(0, "mos_tt")
    if not cand:
        sys.exit("no usable sections")

    print()
    print("=" * 72)
    print(f"{len(cand)} sections x {len(L_LIST)*len(BIAS)} op points"
          + ("   (reusing cp_*.txt where present)" if reuse else ""))
    print("=" * 72)
    tab = {}
    for c in cand:
        a = run(c, reuse=reuse)
        if a is not None:
            tab[c] = a

    if "mos_tt" not in tab:
        sys.exit("\nmos_tt did not run; nothing to compare against")
    ref = tab["mos_tt"]
    I = {c: i for i, c in enumerate(COLS)}
    others = [c for c in tab if c != "mos_tt"]
    dVTH = {c: tab[c][:, I["vth"]] - ref[:, I["vth"]] for c in others}

    # ------------------------------------------------------------------
    # What a corner actually DOES is move VTH and mobility. VTH is a
    # smooth model output, so comparing it says what the corner is. ID
    # in subthreshold is exp(dVTH / n.Ut), so comparing THAT says only
    # that an exponential is an exponential.
    # ------------------------------------------------------------------
    print()
    print("=" * 72)
    print("WHAT EACH SECTION DOES TO VTH")
    print(f"  shift vs mos_tt, in mV, over {ref.shape[0]} bias points")
    print("=" * 72)
    print(f"  {'section':<18}{'median':>10}{'min':>10}{'max':>10}"
          f"{'spread':>10}")
    print("  " + "-" * 58)
    for c in others:
        d = dVTH[c] * 1e3
        print(f"  {c:<18}{np.median(d):9.2f}m{d.min():9.2f}m"
              f"{d.max():9.2f}m{d.max()-d.min():9.2f}m")

    # ---- the design margin, measured where ID is a real current ------
    # Below ~1 nA the OP solution is leakage plus solver residue, and a
    # relative comparison there is noise. 'strong' also demands real
    # inversion, so the number means what a designer thinks it means.
    print()
    print("=" * 72)
    print("DESIGN MARGIN, measured only where ID is a real current")
    print(f"  ID > {ID_FLOOR:g} A and VGS - VTH > 0.2 V")
    print("=" * 72)
    ok = (ref[:, I["ids"]] > ID_FLOOR) & \
         (ref[:, I["vgs"]] - ref[:, I["vth"]] > 0.2)
    print(f"  usable points : {int(ok.sum())} of {ref.shape[0]}")
    keys = ["ids", "gm", "gds", "cgg", "fug"]
    print(f"  {'section':<18}" + "".join(f"{k:>11}" for k in keys))
    print("  " + "-" * (18 + 11 * len(keys)))
    for c in others:
        row = f"  {c:<18}"
        for k in keys:
            d = 100.0 * (tab[c][ok, I[k]] - ref[ok, I[k]]) / ref[ok, I[k]]
            row += f"{np.median(d):10.2f}%"
        print(row)

    print()
    print("  the same corners in SUBTHRESHOLD, for contrast:")
    sub = ref[:, I["vgs"]] - ref[:, I["vth"]] < -0.1
    if sub.any():
        for c in others:
            d = 100.0 * (tab[c][sub, I["ids"]] - ref[sub, I["ids"]]) \
                / ref[sub, I["ids"]]
            ex = d[np.argmax(np.abs(d))]
            print(f"    {c:<18} ID {np.median(d):+10.1f}% median, "
                  f"out to {ex:+.0f}%")
        print("  that is exp(dVTH / n.Ut), not a bigger model difference.")
        print("  it is real, and it is why a weak-inversion design needs")
        print("  the corner table and cannot lean on tt plus a margin.")

    # ---- are the interior corners on the same axis? ------------------
    # If a section's dVTH is a CONSTANT fraction of another's at every
    # bias point, it is the same physical shift scaled down: an interior
    # point on one line, not an independent direction. A sweep of it
    # stores nothing the two ends do not already bound.
    print()
    print("=" * 72)
    print("IS EACH SECTION AN INDEPENDENT DIRECTION?")
    print("  dVTH(section) / dVTH(most extreme section of the same sign)")
    print("  a FLAT ratio means the same shift, scaled: interior point")
    print("=" * 72)
    cor = [c for c in others if is_corner(c)]
    if cor:
        ext_p = max(cor, key=lambda c: np.median(dVTH[c]))
        ext_n = min(cor, key=lambda c: np.median(dVTH[c]))
        interior = []
        for c in others:
            base = ext_p if np.median(dVTH[c]) > 0 else ext_n
            if c == base:
                print(f"  {c:<18} extreme, this is the reference end")
                continue
            with np.errstate(divide="ignore", invalid="ignore"):
                r = dVTH[c] / dVTH[base]
            r = r[np.isfinite(r)]
            if r.size == 0:
                continue
            flat = (r.max() - r.min()) < 0.02
            tag = "FLAT -> interior" if flat else "varies -> own direction"
            print(f"  {c:<18} vs {base:<12} "
                  f"{r.min():.4f} .. {r.max():.4f}   {tag}")
            if flat and is_corner(c):
                interior.append((c, base, float(np.median(r))))
    else:
        interior = []
        ext_p = ext_n = None

    # ---- identical? on VTH, in volts, not on a ratio of currents -----
    print()
    print("=" * 72)
    print("ANY TWO SECTIONS THE SAME DEVICE?")
    print("  max |VTH difference| in volts; identical means under 1 uV")
    print("=" * 72)
    names = list(tab)
    same = []
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            d = np.abs(tab[names[i]][:, I["vth"]]
                       - tab[names[j]][:, I["vth"]]).max()
            if d < 1e-6:
                same.append((names[i], names[j]))
                print(f"  {names[i]:<16} vs {names[j]:<16} "
                      f"{d*1e6:10.4f} uV   IDENTICAL")
    if not same:
        print("  none; every section is a different device")

    # ---- the decision ------------------------------------------------
    print()
    print("=" * 72)
    print("WHICH SWEEPS TO RUN")
    print("=" * 72)
    need = [c for c in others if is_corner(c)]
    drop_stat = [c for c in others if not is_corner(c)]
    for c, base, r in interior:
        if c in need:
            need.remove(c)
    for c in drop_stat:
        print(f"  {c:<18} skipped: Monte Carlo section, not a corner")
        print(f"  {'':<18} it belongs to the mismatch pass")
    for c, base, r in interior:
        print(f"  {c:<18} skipped: {r:.3f} x {base} on the same axis,")
        print(f"  {'':<18} so {base} already bounds it")
    print()
    print(f"  sweeps to run  : {len(need)}")
    for c in need:
        # the flavour first: this script now probes either device, and
        # a command line that leaves it out would sweep the hv one
        print(f"      {c:<14} python3 make_sweep.py {_FLAV} {c}")
    print(f"  sweeps avoided : {len(others) - len(need)}"
          f"   (~{8*(len(others)-len(need))} h)")
    print()
    print("  if you would rather store every section explicitly instead")
    print("  of bounding the interior ones, run make_sweep.py on them")
    print("  too; nothing in the packer or the engine cares.")


if __name__ == "__main__":
    main()
